"""
Export and report generation utilities for PolicyPal AI.
"""

import json
from datetime import datetime

def generate_markdown_report(structured_contract, analysis, metadata: dict) -> str:
    filename = metadata.get("filename", "Contract")
    analysis_type = metadata.get("analysis_type", "Full Analysis")
    num_pages = metadata.get("num_pages", "—")
    contract_type = str(structured_contract.contract_type).replace("ContractType.", "")
    generated_at = datetime.now().strftime("%Y-%m-%d %H:%M:%S")

    critical_risks = [r for r in analysis.risks if r.severity == "High"]
    
    lines = [
        f"# PolicyPal AI — Contract Analysis Report",
        f"",
        f"- **File:** {filename}",
        f"- **Contract Type:** {contract_type}",
        f"- **Pages:** {num_pages}",
        f"- **Analysis Type:** {analysis_type}",
        f"- **Generated At:** {generated_at}",
        f"",
        f"---",
        f"",
        f"## 1. Executive Summary",
        f"",
        f"{analysis.summary.strip() if analysis.summary else 'No summary generated.'}",
        f"",
        f"---",
        f"",
        f"## 2. Risk Evaluation",
        f"",
        f"- **Overall Risk Score:** {analysis.risk_score} / 100",
        f"- **Risk Level:** {analysis.risk_level}",
        f"- **Critical Issues:** {len(critical_risks)}",
        f"",
    ]

    if analysis.risks:
        lines.append("### Flagged Risks")
        for r in analysis.risks:
            lines.append(f"- **[{r.severity.upper()}] {r.category}**: {r.description}")
        lines.append("")
    else:
        lines.append("No significant risks flagged.\n")

    # Question & Answer
    question = metadata.get("question")
    if question and analysis.answer:
        lines.extend([
            f"---",
            f"",
            f"## 3. Inquiry & Explanation",
            f"",
            f"**Question Asked:** {question}",
            f"",
            f"**Answer:**",
            f"{analysis.answer.strip()}",
            f"",
        ])

    # Contracting Parties
    if structured_contract.parties:
        lines.extend([
            f"---",
            f"",
            f"## 4. Contracting Parties",
            f"",
        ])
        for p in structured_contract.parties:
            lines.append(f"- **{p.name}** ({p.role})")
        lines.append("")

    # Party Obligations
    obligations = structured_contract.party_obligations or []
    if obligations:
        lines.extend([
            f"---",
            f"",
            f"## 5. Party Obligations & Commitments",
            f"",
        ])
        for ob in obligations:
            req_str = "Mandatory" if ob.mandatory else "Optional"
            lines.append(f"- **{ob.party}** [{req_str}]: {ob.obligation} *(Section {ob.source_section})*")
        lines.append("")

    # Important Dates
    if structured_contract.important_dates:
        lines.extend([
            f"---",
            f"",
            f"## 6. Key Dates & Deadlines",
            f"",
        ])
        for d in structured_contract.important_dates:
            dtype = str(d.type).replace("DateType.", "").replace("_", " ").title()
            lines.append(f"- **{dtype}**: {d.value} *(Section {d.source_section})*")
        lines.append("")

    # Financial Obligations
    if structured_contract.financial_obligations:
        lines.extend([
            f"---",
            f"",
            f"## 7. Financial Obligations",
            f"",
        ])
        for f in structured_contract.financial_obligations:
            ftype = str(f.type).replace("FinancialObligationType.", "").replace("_", " ").title()
            lines.append(f"- **{ftype}**: {f.amount} — {f.responsible_party} *(Section {f.source_section})*")
        lines.append("")

    # Extracted Clauses
    if structured_contract.clauses:
        lines.extend([
            f"---",
            f"",
            f"## 8. Extracted Contract Clauses ({len(structured_contract.clauses)})",
            f"",
        ])
        for cl in structured_contract.clauses:
            ctype = str(cl.clause_type).replace("ClauseType.", "").replace("_", " ").title()
            lines.append(f"### {ctype} (Section {cl.source_section})")
            lines.append(f"> {cl.original_text.strip()}")
            lines.append("")

    lines.extend([
        f"---",
        f"",
        f"*Report generated by PolicyPal AI.*",
    ])

    return "\n".join(lines)


def generate_json_export(structured_contract, analysis, metadata: dict) -> str:
    data = {
        "metadata": {
            "filename": metadata.get("filename"),
            "contract_type": str(structured_contract.contract_type).replace("ContractType.", ""),
            "pages": metadata.get("num_pages"),
            "analysis_type": metadata.get("analysis_type"),
            "question": metadata.get("question"),
            "exported_at": datetime.now().isoformat(),
        },
        "analysis": {
            "risk_score": analysis.risk_score,
            "risk_level": analysis.risk_level,
            "summary": analysis.summary,
            "answer": analysis.answer,
            "risks": [
                {
                    "category": r.category,
                    "severity": r.severity,
                    "description": r.description,
                }
                for r in (analysis.risks or [])
            ],
        },
        "parties": [
            {"name": p.name, "role": p.role}
            for p in (structured_contract.parties or [])
        ],
        "obligations": [
            {
                "party": ob.party,
                "obligation": ob.obligation,
                "mandatory": ob.mandatory,
                "section": ob.source_section,
            }
            for ob in (structured_contract.party_obligations or [])
        ],
        "important_dates": [
            {
                "type": str(d.type).replace("DateType.", ""),
                "value": d.value,
                "section": d.source_section,
            }
            for d in (structured_contract.important_dates or [])
        ],
        "financial_obligations": [
            {
                "type": str(f.type).replace("FinancialObligationType.", ""),
                "amount": f.amount,
                "responsible_party": f.responsible_party,
                "section": f.source_section,
            }
            for f in (structured_contract.financial_obligations or [])
        ],
        "clauses": [
            {
                "clause_type": str(cl.clause_type).replace("ClauseType.", ""),
                "original_text": cl.original_text,
                "section": cl.source_section,
            }
            for cl in (structured_contract.clauses or [])
        ],
    }

    return json.dumps(data, indent=2, ensure_ascii=False)
